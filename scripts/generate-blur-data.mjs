#!/usr/bin/env node
// Generates the tiny base64 previews used by next/image `placeholder="blur"`.
// Run after scripts/fetch-demo-photos.mjs, or whenever a photo is replaced:
//   node scripts/generate-blur-data.mjs
// Writes src/features/tours/data/image-blur.ts — generated, never edited by hand.

import fs from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

const PHOTO_DIR = path.join(process.cwd(), "public", "images", "tours");
const OUT_FILE = path.join(
  process.cwd(),
  "src",
  "features",
  "tours",
  "data",
  "image-blur.ts",
);

const files = (await fs.readdir(PHOTO_DIR))
  .filter((file) => /\.(jpe?g|png|webp)$/i.test(file))
  .sort();

if (files.length === 0) {
  console.error(
    `No photos in ${PHOTO_DIR}. Run "node scripts/fetch-demo-photos.mjs" first.`,
  );
  process.exit(1);
}

const entries = [];
for (const file of files) {
  const name = file.replace(/\.[^.]+$/, "");
  const buffer = await sharp(path.join(PHOTO_DIR, file))
    .resize(12, 12, { fit: "inside" })
    .webp({ quality: 45 })
    .toBuffer();
  const dataUrl = `data:image/webp;base64,${buffer.toString("base64")}`;
  entries.push([name, dataUrl]);
  console.log(`${name.padEnd(26)} ${buffer.length} bytes`);
}

const body = entries
  .map(
    ([name, dataUrl]) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(dataUrl)},`,
  )
  .join("\n");

await fs.writeFile(
  OUT_FILE,
  `// Generated by scripts/generate-blur-data.mjs — do not edit by hand.\n` +
    `// Tiny previews shown by next/image while the real photo loads.\n\n` +
    `export const imageBlurData: Record<string, string> = {\n${body}\n};\n`,
  "utf8",
);

console.log(
  `\n${entries.length} previews written to ${path.relative(process.cwd(), OUT_FILE)}`,
);
